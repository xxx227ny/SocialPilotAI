import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { createServer } from "vite";

const root = process.cwd();
const read = (...parts) => readFileSync(join(root, ...parts), "utf8");
const server = await createServer({ appType: "custom", logLevel: "silent", root, server: { middlewareMode: true } });

try {
  const state = await server.ssrLoadModule("/src/components/growth/growthOptimizationState.ts");
  const digest = "a".repeat(64);
  const analysis = { product_id: 1, source_context_digest: digest, recommendation_digest: "b".repeat(64) };
  const context = { product_id: 1, context_digest: digest, context_ready: true };
  const policy = { total_budget: 300, target_roas: 2, minimum_platform_share: 0.05, performance_tilt_share: 0.15, maximum_bid_adjustment_pct: 0.2 };
  assert.equal(state.analysisMatchesContext(analysis, context), true);
  assert.equal(state.analysisMatchesContext({ ...analysis, product_id: 2 }, context), false);
  assert.equal(state.analysisMatchesContext({ ...analysis, source_context_digest: "c".repeat(64) }, context), false);
  assert.equal(state.canCreateOptimizationRun(analysis, context, policy, false), true);
  assert.equal(state.canCreateOptimizationRun(analysis, context, policy, true), false);
  assert.equal(state.canCreateOptimizationRun(null, context, policy, false), false);
  assert.equal(state.optimizationIdempotencyKey(analysis, policy), state.optimizationIdempotencyKey(analysis, policy));
  assert.notEqual(state.optimizationIdempotencyKey(analysis, policy), state.optimizationIdempotencyKey(analysis, { ...policy, total_budget: 301 }));
  assert.notEqual(state.optimizationIdempotencyKey(analysis, policy), state.optimizationIdempotencyKey(analysis, policy, 7));
  assert.notEqual(state.optimizationIdempotencyKey(analysis, policy, 7), state.optimizationIdempotencyKey(analysis, policy, 8));
  const run = (id, status) => ({ id, status });
  assert.deepEqual(state.mergeOptimizationRun([run(2, "PROPOSED"), run(1, "SUPERSEDED")], run(2, "ACTIVE")).map((item) => [item.id, item.status]), [[1, "SUPERSEDED"], [2, "ACTIVE"]]);
  assert.equal(state.activeOptimizationRun([run(1, "SUPERSEDED"), run(2, "ACTIVE")]).id, 2);
  const active = { id: 2, product_id: 1, status: "ACTIVE", source_context_digest: digest };
  assert.equal(state.canPreflightSandboxExecution(active, context, false), true);
  assert.equal(state.canPreflightSandboxExecution({ ...active, source_context_digest: "c".repeat(64) }, context, false), false);
  const preflight = { ready: true };
  assert.equal(state.canExecuteSandbox(preflight, true, false), true);
  assert.equal(state.canExecuteSandbox(preflight, false, false), false);
  assert.equal(state.sandboxExecutionIdempotencyKey(active, digest, 0), state.sandboxExecutionIdempotencyKey(active, digest, 0));
  assert.notEqual(state.sandboxExecutionIdempotencyKey(active, digest, 0), state.sandboxExecutionIdempotencyKey(active, digest, 1));
  const execution = (id, status) => ({ id, status });
  assert.deepEqual(state.mergeOptimizationExecution([execution(1, "SUCCEEDED")], execution(1, "ROLLED_BACK")), [execution(1, "ROLLED_BACK")]);
  const automation = { mode: "AUTO_SANDBOX", kill_switch_engaged: false };
  assert.equal(state.canEvaluateAutomation(automation, active, context, false), true);
  assert.equal(state.automationEvaluationBlockReason(automation, active, context, false), null);
  assert.equal(state.automationEvaluationBlockReason(null, active, context, false), "自动化控制尚未读取完成。");
  assert.equal(state.automationEvaluationBlockReason({ ...automation, mode: "MANUAL" }, active, context, false), "请先切换到自动沙箱并保存。");
  assert.equal(state.automationEvaluationBlockReason({ ...automation, kill_switch_engaged: true }, active, context, false), "紧急停止开关已开启，自动评估不会执行。");
  assert.equal(state.automationEvaluationBlockReason(automation, null, context, false), "当前没有已激活的内部方案。");
  assert.equal(state.automationEvaluationBlockReason(automation, { ...active, source_context_digest: "c".repeat(64) }, context, false), "投放数据或内容链已变化，请先生成新的内部方案。");
  assert.equal(state.canEvaluateAutomation({ ...automation, kill_switch_engaged: true }, active, context, false), false);
  assert.equal(state.canEvaluateAutomation({ ...automation, mode: "MANUAL" }, active, context, false), false);
  assert.equal(state.canEvaluateAutomation(automation, active, context, true), false);
  assert.equal(state.automationEvaluationIdempotencyKey(active, digest, 1), state.automationEvaluationIdempotencyKey(active, digest, 1));
  assert.notEqual(state.automationEvaluationIdempotencyKey(active, digest, 1), state.automationEvaluationIdempotencyKey(active, digest, 2));
  const replanCycle = { id: 7, product_id: 1, context_digest: digest, status: "REPLAN_REQUIRED", resolution_status: "UNRESOLVED", resolved_by_optimization_run_id: null };
  assert.equal(state.canRequestQwenReplan(replanCycle, context, false), true);
  assert.equal(state.canRequestQwenReplan({ ...replanCycle, status: "NO_CHANGE" }, context, false), false);
  assert.equal(state.canRequestQwenReplan({ ...replanCycle, product_id: 2 }, context, false), false);
  assert.equal(state.canRequestQwenReplan({ ...replanCycle, context_digest: "c".repeat(64) }, context, false), false);
  assert.equal(state.canRequestQwenReplan(replanCycle, context, true), false);
  assert.equal(state.canRequestQwenReplan({ ...replanCycle, resolution_status: "RESOLVED", resolved_by_optimization_run_id: 9 }, context, false), false);
  assert.equal(state.canRequestQwenReplan({ ...replanCycle, resolved_by_optimization_run_id: 9 }, context, false), false);

  const panel = read("src", "components", "growth", "GrowthOptimizationPanel.tsx");
  const parent = read("src", "components", "GrowthCopilotPanel.tsx");
  const page = read("src", "pages", "GrowthCopilotPage.tsx");
  const api = read("src", "api", "growth.ts");
  const campaignSample = read("public", "samples", "socialpilot-realistic-ad-campaigns-2026-09.csv");
  const campaignRows = campaignSample.trim().split(/\r?\n/);
  assert.match(panel, /setTimeout/);
  assert.doesNotMatch(panel, /setInterval/);
  assert.match(panel, /外部广告账户尚未连接/);
  assert.match(panel, /按精确方案编号激活/);
  assert.match(page, /!isPresentation/);
  assert.match(page, /<GrowthCopilotPanel productId=\{product\.id\}/);
  assert.match(page, /socialpilot\.growthOptimization\.selectedProduct/);
  assert.match(panel, /socialpilot\.growthOptimization\.policy\.\$\{productId\}/);
  assert.match(panel, /restoredPolicy/);
  assert.match(parent, /下载CSV填写模板/);
  assert.match(parent, /SocialPilot-广告投放数据模板\.csv/);
  assert.match(parent, /platform,campaign_name,date,impressions,clicks,conversions,spend,revenue/);
  assert.match(parent, /下载模拟数据（56条）/);
  assert.match(parent, /socialpilot-realistic-ad-campaigns-2026-09\.csv/);
  assert.equal(campaignRows.length, 57);
  assert.equal(campaignRows[0], "platform,campaign_name,date,impressions,clicks,conversions,spend,revenue");
  const parsedCampaignRows = campaignRows.slice(1).map((row) => row.split(","));
  assert.deepEqual([...new Set(parsedCampaignRows.map((row) => row[0]))].sort(), ["Facebook", "Instagram", "Pinterest", "TikTok"]);
  for (const [index, row] of parsedCampaignRows.entries()) {
    assert.equal(row.length, 8, `sample row ${index + 2} must have 8 columns`);
    const impressions = Number(row[3]);
    const clicks = Number(row[4]);
    const conversions = Number(row[5]);
    assert.ok(Number.isInteger(impressions) && impressions >= 0);
    assert.ok(Number.isInteger(clicks) && clicks >= 0 && clicks <= impressions);
    assert.ok(Number.isInteger(conversions) && conversions >= 0 && conversions <= clicks);
    assert.ok(Number(row[6]) >= 0 && Number(row[7]) >= 0);
  }
  assert.match(parent, /投流优化操作步骤/);
  assert.match(page, /AI 投流策略优化/);
  assert.match(parent, /preserveRecommendationIfUnchanged/);
  assert.match(parent, /contextDigestRef\.current !== result\.context_digest/);
  for (const endpoint of ["growth-optimization/plans", "activate", "execution-preflight", "sandbox-executions", "rollback", "automation", "kill-switch", "evaluate", "cycles", "run-once"]) assert.match(api, new RegExp(endpoint));
  assert.match(panel, /我确认仅执行SocialPilot AI沙箱方案/);
  assert.match(panel, /真实广告平台修改为否/);
  assert.match(panel, /按精确执行编号回滚/);
  assert.match(panel, /listGrowthOptimizationExecutions/);
  assert.match(panel, /AUTO_SANDBOX/);
  assert.match(panel, /紧急停止开关/);
  assert.match(panel, /启用持久化ROAS监控计划/);
  assert.match(panel, /监控间隔（秒）/);
  assert.match(panel, /立即运行一次监控周期/);
  assert.match(panel, /REPLAN_REQUIRED/);
  assert.match(panel, /不会偷偷调用千问/);
  assert.match(panel, /监控周期需由外部调度器按次启动/);
  assert.match(panel, /模型调用 0 · 外部修改 否/);
  assert.match(panel, /转到千问重新规划/);
  assert.match(panel, /canRequestQwenReplan/);
  assert.match(parent, /handleQwenReplanRequest/);
  assert.match(parent, /void handlePreflight\(\)/);
  assert.match(parent, /仍需单独确认费用/);
  assert.match(parent, /scrollIntoView/);
  assert.match(parent, /监控周期.*的新千问投流建议已生成/);
  assert.match(api, /source_automation_cycle_id/);
  assert.match(panel, /replanCycleId/);
  assert.match(panel, /listGrowthAutomationCycles/);
  assert.match(panel, /已由方案/);
  assert.match(panel, /resolution_status === "UNRESOLVED"/);
  assert.match(parent, /replanResolved/);
  assert.match(panel, /我确认自动模式仅运行SocialPilot AI沙箱/);
  assert.match(panel, /automationMessage/);
  assert.match(panel, /自动评估当前不可用/);
  assert.match(panel, /仅内部方案 · 外部广告平台未连接/);
  assert.match(panel, /本地安全沙箱/);
  assert.match(panel, /CYCLE_STATUS_LABELS/);
  assert.doesNotMatch(panel, /\{run\.status\}/);
  assert.doesNotMatch(panel, /\{execution\.status\}/);
  assert.doesNotMatch(panel, /access_token|client_secret|Bearer/i);
  console.log("growth optimization: 33 behavior scenarios, 54 static/safety assertions passed");
} finally {
  await server.close();
}
